#!/usr/bin/env python3
"""Build the fonts and Vakint data bundles from the resolved consumers' asset lists.

Only declared resources are included. Dataset names/descriptions and producer
revisions remain in the manifest so future distributions can split this bundle.
"""

import argparse
import base64
import csv
import gzip
import hashlib
import io
import json
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(metadata, output, version, check_catalog=False):
    packages = {package["name"]: package for package in metadata["packages"]}
    payloads, records = {}, []
    for package in sorted(packages.values(), key=lambda package: package["name"]):
        declaration = (package.get("metadata") or {}).get("symbolica-data")
        if declaration is None:
            continue
        root = Path(package["manifest_path"]).parent
        manifest = json.loads((root / declaration["manifest"]).read_text())
        if manifest["schema"] != 1:
            raise ValueError(f"Unsupported asset schema in {package['name']}")
        for entry in manifest["assets"]:
            name = entry["name"]
            path = Path(name)
            if path.is_absolute() or ".." in path.parts or "\\" in name:
                raise ValueError(f"Invalid asset name: {name}")
            source_package = packages[entry.get("package", package["name"])]
            source_root = Path(source_package["manifest_path"]).parent
            if any(record["name"] == name for record in records):
                raise ValueError(f"Duplicate asset name: {name}")
            compatibility = manifest.get("compatibility_only", False)
            if compatibility:
                # Authenticate these declared raw bytes only when explicitly
                # requested; historical reduction packs never enter a wheel.
                content = None
            else:
                content = (source_root / entry["path"]).read_bytes()
                payloads[name] = content
            record = {
                "name": name,
                "description": entry["description"],
                "sha256": entry["sha256"] if compatibility else hashlib.sha256(content).hexdigest(),
                "size": entry["size"] if compatibility else len(content),
                "consumer": package["id"],
                "source": manifest["source"] if compatibility else source_package["id"],
                "source_path": entry["source_path"] if compatibility else entry["path"],
            }
            if compatibility:
                record["compatibility_only"] = True
                record["url"] = manifest["remote_base_url"] + entry["source_path"]
                for field in ("compression", "expanded_size"):
                    if field in entry:
                        record[field] = entry[field]
            elif name.endswith(".gz"):
                expanded = gzip.decompress(content)
                record.update(compression="gzip", expanded_size=len(expanded))
            records.append(record)
    if not records:
        raise ValueError("No external assets found in Cargo metadata")
    records.sort(key=lambda record: record["name"])
    # Keep one small, target-independent catalog in the engine. This lets a
    # WASM host authenticate and supply RustRed data without compiling Vakint.
    expectations = (
        "// Generated by scripts/build_data_bundle.py; payloads live in data.\n"
    )
    expectations += "pub const ALL: &[symbolica_data::Asset] = &[\n"
    for record in records:
        expectations += (
            "    symbolica_data::Asset { "
            + ", ".join(
                f"{field}: {json.dumps(record[field], ensure_ascii=False)}"
                for field in ["name", "sha256", "size", "description"]
            )
            + " },\n"
        )
    expectations += "];\n"
    catalog = ROOT / "src" / "data_assets.rs"
    if check_catalog:
        import re

        fields = re.findall(
            r'(name|sha256|size|description):\s*("(?:[^"\\]|\\.)*"|\d+)',
            catalog.read_text(),
        )
        actual = [
            {key: json.loads(value) for key, value in fields[start : start + 4]}
            for start in range(0, len(fields), 4)
        ]
        expected = [
            {
                field: record[field]
                for field in ["name", "sha256", "size", "description"]
            }
            for record in records
        ]
        if actual != expected:
            raise ValueError(
                "Compiled asset catalog differs from dependency sources; regenerate it before building"
            )
    else:
        catalog.write_text(expectations)
    wheels = []
    for distribution, bundle, prefix in [
        ("symbolica-fonts", "fonts", "render/fonts/"),
        ("symbolica-vakint-data", "vakint-data", "vakint/"),
    ]:
        selected = [
            record for record in records
            if record["name"].startswith(prefix) and record["name"] in payloads
        ]
        if selected:
            wheels.append(
                write_bundle(
                    {record["name"]: payloads[record["name"]] for record in selected},
                    selected,
                    output,
                    version,
                    distribution,
                    bundle,
                )
            )
    if sum(
        len(record)
        for record in [
            [entry for entry in records if entry["name"].startswith("render/fonts/")],
            [entry for entry in records if entry["name"].startswith("vakint/")],
        ]
    ) != len(records):
        raise ValueError("An asset has no declared resource distribution")
    return wheels


def write_bundle(payloads, records, output, version, distribution, bundle):
    manifest = {"schema": 1, "bundle": bundle, "version": version, "assets": records}
    manifest_bytes = (json.dumps(manifest, indent=2) + "\n").encode()
    data_root = output / bundle
    data_root.mkdir(parents=True, exist_ok=True)
    for name, content in payloads.items():
        destination = data_root / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(content)
    (data_root / "manifest.json").write_bytes(manifest_bytes)

    module = distribution.replace("-", "_")
    info = f"{module}-{version}.dist-info"
    # Each distribution owns a separate subtree. In particular, resource wheels
    # must never replace the engine's symbolica/__init__.py or share a manifest.
    package_data = f"symbolica/_data/{bundle}"
    files = {f"{package_data}/{name}": content for name, content in payloads.items()}
    files[f"{package_data}/manifest.json"] = manifest_bytes
    files[f"{info}/METADATA"] = (
        f"Metadata-Version: 2.3\nName: {distribution}\nVersion: {version}\n"
        f"Summary: External {bundle} resources for Symbolica\n"
        "Requires-Python: >=3.9\nLicense: See bundled third-party notices\n\n"
    ).encode()
    files[f"{info}/WHEEL"] = (
        # Place portable data beside the native package even when Python's
        # purelib and platlib directories differ.
        b"Wheel-Version: 1.0\nGenerator: symbolica-community data bundler\nRoot-Is-Purelib: false\nTag: py3-none-any\n"
    )
    for license_path in [ROOT / "LICENSE", *sorted((ROOT / "licenses").glob("*"))]:
        if license_path.is_file():
            files[f"{info}/licenses/{license_path.name}"] = license_path.read_bytes()
    record = io.StringIO(newline="")
    writer = csv.writer(record, lineterminator="\n")
    for name, content in sorted(files.items()):
        digest = (
            base64.urlsafe_b64encode(hashlib.sha256(content).digest())
            .rstrip(b"=")
            .decode()
        )
        writer.writerow([name, "sha256=" + digest, len(content)])
    writer.writerow([f"{info}/RECORD", "", ""])
    files[f"{info}/RECORD"] = record.getvalue().encode()
    wheel = output / f"{module}-{version}-py3-none-any.whl"
    with zipfile.ZipFile(
        wheel, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
    ) as archive:
        for name, content in sorted(files.items()):
            entry = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            entry.external_attr = 0o644 << 16
            archive.writestr(
                entry, content, compress_type=zipfile.ZIP_DEFLATED, compresslevel=9
            )
    with zipfile.ZipFile(wheel) as archive:
        assert archive.testzip() is None
    print(f"Built {wheel}: {wheel.stat().st_size:,} bytes; {len(records)} assets")
    return wheel


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--metadata", type=Path, help="Use previously resolved Cargo metadata"
    )
    parser.add_argument("--out", type=Path, default=ROOT / "dist")
    parser.add_argument("--version", help="Override the distribution version")
    parser.add_argument(
        "--check-catalog",
        action="store_true",
        help="Verify the checked-in expectations instead of regenerating them",
    )
    args = parser.parse_args()
    metadata = (
        json.loads(args.metadata.read_text())
        if args.metadata
        else json.loads(
            subprocess.check_output(
                ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT
            )
        )
    )
    if args.version is None:
        import re

        args.version = re.search(
            r'^version\s*=\s*"([^\"]+)"',
            (ROOT / "pyproject.toml").read_text(),
            re.MULTILINE,
        )[1]
    args.out.mkdir(parents=True, exist_ok=True)
    build(metadata, args.out, args.version, args.check_catalog)
